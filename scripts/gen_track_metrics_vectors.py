"""Write the vectors the client's Dart track maths is pinned to (issue #366).

The client edits and splits an end-to-end-encrypted activity's track on the
device, so it carries a Dart port (``flutter_client/lib/src/track_metrics/``)
of the server's track maths. Python is the source of truth: this script runs
the Python functions over a fixed set of inputs and writes what they return to
``flutter_client/test/fixtures/track_metrics_vectors.json``. The Dart tests
assert the port reproduces every vector; ``tests/test_track_metrics_parity.py``
fails when the committed file no longer matches what this script produces.

Run from the repo root after changing any of the functions below, and commit
the result::

    python scripts/gen_track_metrics_vectors.py

For a Dart implementer — the file, without reading any Python:

* The top level holds ``_schema`` (these notes, condensed), ``constants`` (the
  Python constants by their Python names) and one section per function. A
  section is a list of cases ``{"name", "input", "expected"}``; ``name`` says
  what the case exercises. A case expected to raise has ``"expected_error"``
  instead of ``"expected"``.
* Floats are compared within 1e-6; ints, strings, booleans and nulls exactly.
  A field documented as int is written without a decimal point; every other
  number is a double even when it looks integral (``100.0``).
* A point is ``[lat, lng, elev]``, ``elev`` null when missing. A raw input
  elevation that is not finite or lies outside [-20000, 20000] m is treated as
  missing when the point is built (Python ``TrackPoint.__post_init__``); the
  vectors carry ``65535`` and ``-25000`` for that, JSON having no NaN.
* Python semantics a port must mirror exactly are listed in ``_SCHEMA`` below.

Deterministic: every random series comes from ``tests/elevation_bench`` with a
fixed seed and is rounded (Python's correctly-rounded ``round``) before use, so
the inputs are exact decimals whatever the platform's libm.
"""
