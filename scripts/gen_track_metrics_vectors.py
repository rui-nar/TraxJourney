# ── Inputs ───────────────────────────────────────────────────────────────────

def _r(values: List[float], digits: int) -> List[float]:
    return [round(v, digits) for v in values]


def _series(track: gen.Track) -> Dict[str, List[float]]:
    """A bench track as exact-decimal ``{elevations, distances_km}``."""
    elevations, distances, _ = track
    return {"elevations": _r(elevations, 2), "distances_km": _r(distances, 6)}


def _walk(count: int, spacing_m: float, bearing_deg: float = 30.0,
          start=(45.83, 6.86)) -> List[List[float]]:
    """``count`` latlngs from ``start`` along a bearing, 5 decimals as decoded."""
    lat, lng = start
    out = []
    dy = spacing_m * math.cos(math.radians(bearing_deg)) / 111_320.0
    for _ in range(count):
        out.append([round(lat, 5), round(lng, 5)])
        dx = spacing_m * math.sin(math.radians(bearing_deg)) / (
            111_320.0 * math.cos(math.radians(lat)))
        lat += dy
        lng += dx
    return out


def _points(latlngs: List[List[float]], elevs: List[Optional[float]]) -> List[list]:
    return [[lat, lng, e] for (lat, lng), e in zip(latlngs, elevs)]


def _track_points(p: list) -> List[te.TrackPoint]:
    return [te.TrackPoint(lat=lat, lng=lng, elev=e) for lat, lng, e in p]


def _as_lists(points: List[te.TrackPoint]) -> List[list]:
    return [[p.lat, p.lng, p.elev] for p in points]


def _with_dropouts(elevations: List[float], runs) -> List[float]:
    """The pre-#374 stored form: runs of the ``0.0`` "no reading" sentinel."""
    out = list(elevations)
    for start, length in runs:
        for i in range(start, start + length):
            out[i] = 0.0
    return out


