def build_vectors() -> Dict[str, Any]:
    """Every vector, as plain JSON types."""
    constants = python_constants()
    # Derived, written so a mismatch in the port's formula shows on its own.
    constants["_NOISE_DIFFERENCE_SCALE"] = {
        str(k): v for k, v in te._NOISE_DIFFERENCE_SCALE.items()}
    # The dropout rule's, from the migration; not in elevation_gain.dart.
    migration = _sentinel_migration()
    constants["_SENTINEL_MIN_GRADE"] = migration._SENTINEL_MIN_GRADE
    constants["_SENTINEL_MIN_STEP_M"] = migration._SENTINEL_MIN_STEP_M
    data: Dict[str, Any] = {"_schema": _SCHEMA, "constants": constants}
    for section, build in _SECTIONS.items():
        cases = build()
        names = [c["name"] for c in cases]
        assert len(names) == len(set(names)), f"duplicate case name in {section}"
        data[section] = cases
    return data


def _is_leaf(value: Any) -> bool:
    """A scalar, or a list of numbers, nulls and such lists (one line each).
    A list of strings (the schema notes) is not: one string per line."""
    if isinstance(value, list):
        return all(_is_leaf(v) and not isinstance(v, (dict, str)) for v in value)
    return not isinstance(value, dict)


def render(value: Any, indent: int = 0) -> str:
    """JSON, sorted keys, one line per leaf list so long series stay compact."""
    pad = "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{pad}{json.dumps(k)}: {render(value[k], indent + 1)}"
                 for k in sorted(value)]
        return "{\n" + ",\n".join(items) + "\n" + "  " * indent + "}"
    if isinstance(value, list) and not _is_leaf(value):
        items = [pad + render(v, indent + 1) for v in value]
        return "[\n" + ",\n".join(items) + "\n" + "  " * indent + "]"
    return json.dumps(value, separators=(",", ":"), allow_nan=False)


